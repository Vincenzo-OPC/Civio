def check_code(w, m, c):
    """Return True when the coded error type describes the misspelling."""
    def sub(a, b):  # a is b with letters removed
        it = iter(b); return len(a) < len(b) and all(ch in it for ch in a)
    if c == I:
        return w.replace("ie", "ei", 1) == m or w.replace("ei", "ie", 1) == m
    if c == D:
        f = lambda s: "".join(ch for k, ch in enumerate(s) if k == 0 or s[k - 1] != ch)
        return f(w) == f(m) and w != m
    if c in (X, S):
        return sub(m, w)
    return True
